/**
 * Helper to retrieve service details by primary slug or alias
 */
export function getServiceBySlug(slug: string): ServiceDetail | undefined {
  if (!slug) return undefined;
  const normalizedSlug = slug.toLowerCase().trim();

  // Direct lookup
  if (SERVICES_DETAIL_DATA[normalizedSlug]) {
    return SERVICES_DETAIL_DATA[normalizedSlug];
  }

  // Alias lookup
  for (const key in SERVICES_DETAIL_DATA) {
    const service = SERVICES_DETAIL_DATA[key];
    if (service.aliases && service.aliases.includes(normalizedSlug)) {
      return service;
    }
  }

  return undefined;
}
